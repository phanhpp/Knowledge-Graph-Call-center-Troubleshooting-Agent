def _fields(message):
    """A saved message's fields, whether stored flat or in LangChain's {"kwargs": {...}} form."""
    if not isinstance(message, dict):
        return {}
    return message.get("kwargs", message)


def perform_eval(run):
    outputs = run.get("outputs") or {}
    messages = outputs.get("messages") or []
    if not messages:
        return {}
    reply = _fields(messages[-1])
    citations = (reply.get("additional_kwargs") or {}).get("citations") or [] # get the citation argument
    if not citations:
        return {}
    return {"citations_exist": int(all(c in VALID_IDS for c in citations))}
