"""Regenerate the valid-ID list inside citations_exist.py from data/.

Run after changing actions, rules or knowledge-base articles, then paste citations_exist.py into
the LangSmith evaluator again:

    uv run python eval/online/utils/build_valid_ids.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]  # the project root
TARGET = Path(__file__).resolve().parents[1] / "citations_exist.py"  # eval/online/
START = "# --- valid IDs (generated by build_valid_ids.py; do not edit by hand) ---"
END = "# --- end of valid IDs ---"


def valid_ids() -> list[str]:
    """Every ID a reply may cite: actions, rules and knowledge-base articles."""
    ids = []
    for file, key in [("actions.json", "action_id"), ("rules.json", "rule_id"), ("kb_articles.json", "article_id")]:
        ids += [record[key] for record in json.loads((ROOT / "data" / file).read_text())]
    return sorted(ids)


def render(ids: list[str]) -> str:
    """The VALID_IDS block, eight IDs per line."""
    rows = [", ".join(f'"{i}"' for i in ids[n:n + 8]) + "," for n in range(0, len(ids), 8)]
    return "\n".join([START, "VALID_IDS = {", *(f"    {row}" for row in rows), "}", END])


def main() -> None:
    text = TARGET.read_text()
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    ids = valid_ids()
    TARGET.write_text(before + render(ids) + after)
    print(f"Wrote {len(ids)} valid IDs into {TARGET.name}")


if __name__ == "__main__":
    main()
